    /**
     * Generate a JUnit4 test with LLM and compile it.
     *
     * This is the stable API you can call from your Excel loop.
     * It intentionally does NOT execute MuJava/TestRunner9 and does NOT fill killed/live fields.
     */
    public static Result generateAndCompile(Request request) throws Exception {
        validateRequest(request);

        RuntimeConfig runtimeConfig = loadRuntimeConfig();
        ModelConfig modelConfig = loadModelConfig();

        Result result = new Result();
        result.targetClassName = request.targetClassName;
        result.methodSignature = request.methodSignature;
        result.mutantName = request.mutantName;

        JSONObject fullJson = new JSONObject(readUtf8(Paths.get(request.outputJsonPath)));
        PromptEvidence evidence = PromptEvidence.fromFullOutput(fullJson);

        String projectCp = LocalJarFinder.buildProjectClasspath(request.sourceModuleHome);
        if (projectCp == null) {
            projectCp = "";
        }

        Path llmsRoot = Paths.get(request.resultModuleHome, MutationSystem.TESTSET_MODE_LLMS);
        Path testSrcRoot = llmsRoot.resolve("src");
        Path testClassesRoot = llmsRoot.resolve("classes");
        Path reportRoot = llmsRoot.resolve("report");
        Path apiCacheRoot = reportRoot.resolve("llm_api_cache");
        Files.createDirectories(testSrcRoot);
        Files.createDirectories(testClassesRoot);
        Files.createDirectories(reportRoot);
        if (!runtimeConfig.forceRegenerate) {
            Files.createDirectories(apiCacheRoot);
        }

        result.reportDir = reportRoot.toAbsolutePath().normalize().toString();

        String testSetName = buildGeneratedTestFqn(request.targetClassName, request.mutantName);
        result.testSetName = testSetName;
        Path javaFile = toJavaFile(testSrcRoot, testSetName);
        result.testJavaFile = javaFile.toAbsolutePath().normalize().toString();

        Path compactEvidenceFile = reportRoot.resolve(fileBaseName(testSetName) + "__compact_evidence.json");
        Path promptFile = reportRoot.resolve(fileBaseName(testSetName) + "__prompt.txt");
        Path resultJsonlFile = reportRoot.resolve("llm_generation_results.jsonl");
        result.resultJsonlFile = resultJsonlFile.toAbsolutePath().normalize().toString();

        writeText(compactEvidenceFile, evidence.toJson().toString(2));

        if (evidence.skipTestGeneration) {
            result.compiled = false;
            result.compileRounds = 0;
            result.failureReason = "Skipped by output.json: " + oneLine(evidence.skipReason);
            writeGenerationSummary(reportRoot.resolve(fileBaseName(testSetName) + "__generation_summary.txt"), result);
            appendResultJsonl(resultJsonlFile, result);
            return result;
        }

        LlmClient client = new LlmClient(modelConfig);

        String prompt = buildInitialPrompt(request, evidence, testSetName);
        prompt = enforcePromptBudget(prompt, runtimeConfig, fileBaseName(testSetName), "initial");
        writeText(promptFile, prompt);

        String candidateCode = null;
        String lastCompileError = "";
        int rounds = 0;

        for (int attempt = 0; attempt <= request.maxRepairRounds; attempt++) {
            rounds++;
            String rawResponse;
            Path responseFile = reportRoot.resolve(fileBaseName(testSetName) + "__response_" + attempt + ".json");
            if (attempt == 0) {
                /*
                 * Initial generation cache policy:
                 * forceRegenerate=true  -> fresh API.
                 * forceRegenerate=false -> response_0.json -> llm_api_cache -> fresh API.
                 */
                LlmCallResult call = generateInitialLlmResponse(
                        client,
                        prompt,
                        responseFile,
                        apiCacheRoot,
                        modelConfig,
                        runtimeConfig
                );
                rawResponse = call.response;
            } else {
                String repairPrompt = buildRepairPrompt(
                        request,
                        evidence,
                        testSetName,
                        candidateCode,
                        lastCompileError
                );
                repairPrompt = enforcePromptBudget(
                        repairPrompt,
                        runtimeConfig,
                        fileBaseName(testSetName),
                        "repair-" + attempt
                );
                writeText(reportRoot.resolve(fileBaseName(testSetName) + "__repair_" + attempt + "_prompt.txt"), repairPrompt);

                /*
                 * Repair generation must be fresh. If javac already rejected the
                 * previous code, reusing stale response_1/response_2 or prompt-cache
                 * can repeat the same compile error forever.
                 */
                LlmCallResult call = generateFreshLlmResponse(client, repairPrompt, responseFile);
                rawResponse = call.response;
            }

            candidateCode = extractJavaCode(rawResponse);
            candidateCode = normalizeGeneratedTestCode(candidateCode, testSetName);

            if (candidateCode == null || candidateCode.trim().isEmpty()) {
                lastCompileError = "LLM returned empty code.";
                writeText(
                        reportRoot.resolve(fileBaseName(testSetName) + "__compile_error_" + attempt + ".txt"),
                        lastCompileError
                );
                continue;
            }

            writeText(javaFile, candidateCode);

            try {
                compileGeneratedTestPortable(
                        request.sourceModuleHome,
                        javaFile,
                        testClassesRoot,
                        projectCp
                );
                result.compiled = true;
                result.failureReason = "";
                break;
            } catch (Exception compileFailure) {
                lastCompileError = String.valueOf(compileFailure.getMessage());
                writeText(
                        reportRoot.resolve(fileBaseName(testSetName) + "__compile_error_" + attempt + ".txt"),
                        lastCompileError
                );
            }
        }

        result.compileRounds = rounds;
        if (!result.compiled) {
            result.failureReason = "Compilation failed after repair rounds. Last error: " + oneLine(lastCompileError);
        }

        writeGenerationSummary(reportRoot.resolve(fileBaseName(testSetName) + "__generation_summary.txt"), result);
        appendResultJsonl(resultJsonlFile, result);
        return result;
    }

    /**
     * Backward-compatible name for older callers. Despite the name, this method now only generates and compiles.
     */
    public static Result generateCompileAndRun(Request request) throws Exception {
        return generateAndCompile(request);
    }

    private static LlmCallResult generateInitialLlmResponse(LlmClient client,
                                                            String prompt,
                                                            Path responseFile,
                                                            Path apiCacheRoot,
                                                            ModelConfig modelConfig,
                                                            RuntimeConfig runtimeConfig) throws Exception {
        if (!runtimeConfig.forceRegenerate && Files.isRegularFile(responseFile)) {
            LlmCallResult result = new LlmCallResult();
            result.response = readUtf8(responseFile);
            result.responseFileHit = true;
            result.cacheHit = true;
            return result;
        }

        Path cacheFile = apiCacheFileFor(apiCacheRoot, modelConfig, prompt);
        if (!runtimeConfig.forceRegenerate && Files.isRegularFile(cacheFile)) {
            LlmCallResult result = new LlmCallResult();
            result.response = readUtf8(cacheFile);
            result.apiCacheHit = true;
            result.cacheHit = true;
            writeText(responseFile, result.response);
            return result;
        }

        LlmCallResult result = generateFreshLlmResponse(client, prompt, responseFile);
        if (!runtimeConfig.forceRegenerate) {
            writeText(cacheFile, result.response);
        }
        return result;
    }

    private static LlmCallResult generateFreshLlmResponse(LlmClient client,
                                                          String prompt,
                                                          Path responseFile) throws Exception {
        LlmCallResult result = new LlmCallResult();
        result.freshApiCall = true;
        result.response = client.generate(prompt);
        writeText(responseFile, result.response);
        return result;
    }

    private static Path apiCacheFileFor(Path apiCacheRoot, ModelConfig modelConfig, String prompt) {
        String fingerprint = firstNonBlank(modelConfig.apiUrl, "")
                + "\nMODEL=" + firstNonBlank(modelConfig.model, "")
                + "\nTEMP=" + modelConfig.temperature
                + "\nMAXTOKENS=" + modelConfig.maxTokens
                + "\nPROMPT=\n" + (prompt == null ? "" : prompt);
        return apiCacheRoot.resolve(sha256Hex(fingerprint) + ".json");
    }

    private static String enforcePromptBudget(String prompt,
                                              RuntimeConfig cfg,
                                              String taskId,
                                              String phase) {
        if (prompt == null) {
            return "";
        }
        if (cfg == null) {
            return prompt;
        }
        int maxChars = cfg.maxInputChars;
        if (maxChars <= 0 && cfg.maxInputTokens > 0) {
            // Conservative approximation for English/code/JSON prompts.
            maxChars = cfg.maxInputTokens * 3;
        }
        if (maxChars <= 0 || prompt.length() <= maxChars) {
            return prompt;
        }

        String policy = firstNonBlank(cfg.oversizePromptPolicy, DEFAULT_OVERSIZE_PROMPT_POLICY).toLowerCase(Locale.ROOT);
        int estimatedTokens = estimateTokens(prompt);
        String msg = "[LLM-PROMPT-BUDGET] taskId=" + taskId
                + " phase=" + phase
                + " policy=" + policy
                + " charsBefore=" + prompt.length()
                + " estimatedTokensBefore=" + estimatedTokens
                + " maxInputTokens=" + cfg.maxInputTokens
                + " maxInputChars=" + maxChars;
        System.err.println(msg);

        if ("fail".equals(policy)) {
            throw new IllegalArgumentException("Prompt too large before LLM call. " + msg);
        }

        String truncated = truncatePromptKeepHeadAndTail(prompt, maxChars);
        System.err.println("[LLM-PROMPT-BUDGET] taskId=" + taskId
                + " phase=" + phase
                + " charsAfter=" + truncated.length()
                + " estimatedTokensAfter=" + estimateTokens(truncated));
        return truncated;
    }

    private static int estimateTokens(String text) {
        if (text == null || text.isEmpty()) {
            return 0;
        }
        return Math.max(1, (int) Math.ceil(text.length() / 3.0));
    }

    private static String truncatePromptKeepHeadAndTail(String prompt, int maxChars) {
        if (prompt == null || prompt.length() <= maxChars) {
            return prompt == null ? "" : prompt;
        }
        String marker = "\n\n/* <PROMPT_TRUNCATED_BY_LOCAL_BUDGET> "
                + "Large evidence was removed to satisfy the configured max input budget. "
                + "Preserve hard requirements, target metadata, javac error, previous code, and key invocation/assertion evidence. "
                + "</PROMPT_TRUNCATED_BY_LOCAL_BUDGET> */\n\n";
        int remaining = Math.max(0, maxChars - marker.length());
        int head = (int) (remaining * 0.65);
        int tail = remaining - head;
        String h = prompt.substring(0, Math.min(head, prompt.length()));
        String t = prompt.substring(Math.max(0, prompt.length() - tail));
        return h + marker + t;
    }

    private static String sha256Hex(String text) {
        try {
            MessageDigest md = MessageDigest.getInstance("SHA-256");
            byte[] digest = md.digest((text == null ? "" : text).getBytes(StandardCharsets.UTF_8));
            StringBuilder sb = new StringBuilder(digest.length * 2);
            for (byte b : digest) {
                sb.append(String.format(Locale.ROOT, "%02x", b & 0xff));
            }
            return sb.toString();
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 is not available", e);
        }
    }

