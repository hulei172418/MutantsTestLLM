    private static void appendCompilerSpecificDiagnosis(StringBuilder sb, PromptEvidence e, String compileError) {
        String err = compileError == null ? "" : compileError.toLowerCase(Locale.ROOT);
        JSONObject receiver = e == null ? null : e.invocation.optJSONObject("receiver");
        String strategy = receiver == null ? "" : receiver.optString("strategy", "");
        if (receiver != null && receiver.length() > 0) {
            sb.append("Static receiver/construction evidence:\n");
            sb.append(receiver.toString(2)).append("\n\n");
        }
        if (e != null && e.publicApiEvidence.length() > 0) {
            sb.append("Static public API evidence:\n");
            sb.append(e.publicApiEvidence.toString(2)).append("\n\n");
        }
        if (e != null && e.observablePlan.length() > 0) {
            sb.append("Static observable plan:\n");
            sb.append(e.observablePlan.toString(2)).append("\n\n");
        }
        if ("STATIC_FACTORY_BUILDER".equals(strategy) || looksLikeFactoryBuilderError(err)) {
            String setup = e == null ? "" : firstSetupStatement(e.invocation);
            String terminal = receiver == null ? "" : receiver.optString("builderTerminalMethod", "");
            String factory = receiver == null ? "" : receiver.optString("factoryMethod", "");
            sb.append("Compiler-specific diagnosis:\n");
            sb.append("- The previous code used an invalid constructor or builder terminal method.\n");
            if (!factory.isEmpty()) {
                sb.append("- Use the static factory method from evidence: ").append(factory).append(".\n");
            }
            if (!terminal.isEmpty()) {
                sb.append("- The builder terminal method from evidence is ").append(terminal).append("(); use it exactly.\n");
            }
            if (!setup.isEmpty()) {
                sb.append("- Use this setup statement exactly unless syntax requires line wrapping: ").append(setup).append("\n");
            }
            sb.append("- Do not call new TargetClass(), new Builder(), or builder.build() unless those exact forms appear in INVOCATION.setup.\n\n");
        }
        if (err.contains("cannot find symbol") && err.contains("method") && e != null && e.publicApiEvidence.length() > 0) {
            sb.append("Compiler-specific diagnosis:\n");
            sb.append("- The previous code called a method that does not exist on the receiver.\n");
            sb.append("- Use exact method names from PUBLIC_API.availablePublicMethods / availableSetupMethods; do not guess JavaBean names such as getX(), isX(), or setX().\n");
            if (e.observablePlan.length() > 0) {
                sb.append("- If OBSERVABLE_PLAN.observableCall is present, use that public call instead of inventing getters/readers.\n");
            }
            sb.append("\n");
        }
        if (err.contains("overridden method is final") || err.contains("must be first statement") || err.contains("does not override abstract method")) {
            sb.append("Compiler-specific diagnosis:\n");
            sb.append("- The previous test stub/subclass is invalid. Do not override final methods; implement all abstract methods listed in receiver.abstractMethodsToImplement; any super(...) call must be the first statement in the constructor.\n\n");
        }
    }

    private static String firstSetupStatement(JSONObject invocation) {
        if (invocation == null) {
            return "";
        }
        JSONArray arr = invocation.optJSONArray("setup");
        if (arr == null || arr.length() == 0) {
            return "";
        }
        return arr.optString(0, "").trim();
    }

    private enum CompileErrorKind {
        FACTORY_BUILDER_MISMATCH,
        TEST_STUB_MISMATCH,
        MISSING_CLASS_OR_IMPORT,
        CONSTRUCTOR_MISMATCH,
        ABSTRACT_INSTANTIATION,
        METHOD_NOT_FOUND,
        INCOMPATIBLE_TYPES,
        PACKAGE_ACCESS,
        OTHER
    }

    private static CompileErrorKind classifyCompileError(String error) {
        String e = error == null ? "" : error.toLowerCase(Locale.ROOT);
        if (e.contains("overridden method is final") || e.contains("must be first statement in constructor") || e.contains("does not override abstract method")) {
            return CompileErrorKind.TEST_STUB_MISMATCH;
        }
        if (looksLikeFactoryBuilderError(e)) {
            return CompileErrorKind.FACTORY_BUILDER_MISMATCH;
        }
        if (e.contains("cannot be instantiated") || e.contains("is abstract") || e.contains("abstract")) {
            return CompileErrorKind.ABSTRACT_INSTANTIATION;
        }
        if (e.contains("constructor") && (e.contains("cannot be applied") || e.contains("undefined"))) {
            return CompileErrorKind.CONSTRUCTOR_MISMATCH;
        }
        if (e.contains("cannot find symbol") && e.contains("method")) {
            return CompileErrorKind.METHOD_NOT_FOUND;
        }
        if (e.contains("cannot be applied to") && e.contains("method")) {
            return CompileErrorKind.METHOD_NOT_FOUND;
        }
        if (e.contains("cannot find symbol") && (e.contains("class") || e.contains("variable") || e.contains("package"))) {
            return CompileErrorKind.MISSING_CLASS_OR_IMPORT;
        }
        if (e.contains("incompatible types") || e.contains("no suitable method found for assert")) {
            return CompileErrorKind.INCOMPATIBLE_TYPES;
        }
        if (e.contains("is not public") || e.contains("has protected access") || e.contains("private access")
                || e.contains("cannot be accessed from outside package")) {
            return CompileErrorKind.PACKAGE_ACCESS;
        }
        return CompileErrorKind.OTHER;
    }

    private static boolean looksLikeFactoryBuilderError(String e) {
        if (e == null) {
            return false;
        }
        if (e.contains("builder() has private access") || e.contains("builder() is private")) {
            return true;
        }
        if (e.contains("builder()") && e.contains("private access")) {
            return true;
        }
        if (e.contains("builder") && e.contains("private access")) {
            return true;
        }
        if (e.contains("cannot find symbol") && e.contains("method build")) {
            return true;
        }
        if (e.contains("symbol:   method build") || e.contains("symbol: method build")) {
            return true;
        }
        if (e.contains("constructor") && e.contains("cannot be applied") && (e.contains("textstyle") || e.contains("builder"))) {
            return true;
        }
        return false;
    }

