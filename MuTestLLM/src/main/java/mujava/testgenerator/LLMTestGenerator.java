    private static String buildRepairPrompt(Request request,
                                            PromptEvidence e,
                                            String testSetName,
                                            String lastCode,
                                            String compileError) {
        String packageName = packageNameOf(testSetName);
        String simpleClassName = simpleNameOf(testSetName);
        CompileErrorKind kind = classifyCompileError(compileError);

        StringBuilder sb = new StringBuilder(8192);
        sb.append("Repair the Java JUnit4 test so it compiles in the existing project.\n");
        sb.append("Return only Java source code. Do not include markdown fences or explanations.\n\n");

        sb.append("Non-negotiable constraints:\n");
        sb.append("- public class name must be: ").append(simpleClassName).append("\n");
        if (!packageName.isEmpty()) {
            sb.append("- package declaration must be: package ").append(packageName).append(";\n");
        }
        sb.append("- JUnit4 only; no extra third-party test libraries.\n");
        sb.append("- Preserve intent: kill mutant ").append(request.mutantName)
                .append(" for method ").append(request.methodSignature).append(".\n");
        sb.append("- Include at least one requiredToKill assertion or equivalent mutation-sensitive assertion when possible.\n\n");

        sb.append("Javac error category: ").append(kind.name()).append("\n");
        sb.append("Javac error:\n").append(compileError == null ? "" : compileError).append("\n\n");

        appendCompilerSpecificDiagnosis(sb, e, compileError);

        sb.append("Repair focus:\n");
        switch (kind) {
            case MISSING_CLASS_OR_IMPORT:
                sb.append("- Fix package/imports/class names using INVOCATION.imports and target package.\n");
                sb.append("- Do not invent classes not listed in the evidence or project/JDK/JUnit4.\n");
                break;
            case TEST_STUB_MISMATCH:
                sb.append("- The generated test subclass/stub is invalid. Follow INVOCATION.receiver.testStubClassTemplate and testStubConstructorTemplate exactly if present.\n");
                sb.append("- Do not override final methods; only override allowed abstract methods. Put super(...) first in any constructor.\n");
                break;
            case FACTORY_BUILDER_MISMATCH:
                sb.append("- The failure is caused by an invalid factory/builder construction. Use INVOCATION.setup exactly.\n");
                sb.append("- Do not call new TargetClass() when the receiver strategy says STATIC_FACTORY_BUILDER.\n");
                sb.append("- Do not call new Builder() if the builder constructor is private. Use receiver.factoryMethod instead.\n");
                sb.append("- Use receiver.builderTerminalMethod exactly; do not guess build() when the evidence says get().\n");
                break;
            case CONSTRUCTOR_MISMATCH:
                sb.append("- Fix constructor arguments using INVOCATION.setup and INVOCATION.call.\n");
                sb.append("- If entry.invocationKind is CONSTRUCTOR_INVOCATION, instantiate with new B(...).\n");
                sb.append("- If receiver.strategy is STATIC_FACTORY_BUILDER, ignore constructor guessing and use INVOCATION.setup exactly.\n");
                break;
            case ABSTRACT_INSTANTIATION:
                sb.append("- The receiver/test stub is abstract or not directly instantiable. Follow INVOCATION.receiver.strategy exactly.\n");
                sb.append("- If javac says an anonymous class does not override an abstract method, implement every method listed in INVOCATION.receiver.abstractMethodsToImplement.\n");
                sb.append("- Do not override methods listed in INVOCATION.receiver.forbiddenOverrides.\n");
                sb.append("- If strategy is CONCRETE_SUBCLASS_INHERITED_METHOD, instantiate runtimeReceiverClass; do not create an anonymous subclass.\n");
                sb.append("- If strategy is TEST_STUB_SUBCLASS or ANONYMOUS_SUBCLASS, implement all required abstract methods supplied by the evidence.\n");
                break;
            case METHOD_NOT_FOUND:
                sb.append("- Remove calls to non-existing methods. Use exact method names from PUBLIC_API.availablePublicMethods / availableSetupMethods.\n");
                sb.append("- Do not invent getters/setters/readers. If OBSERVABLE_PLAN.observableCall exists, use it as the public observable.\n");
                sb.append("- If the entry is a constructor, do not call the constructor like a normal method.\n");
                sb.append("- If a builder terminal method is missing, use receiver.builderTerminalMethod exactly; for example use get() if build() does not exist.\n");
                break;
            case INCOMPATIBLE_TYPES:
                sb.append("- Fix assertEquals operand types. Use ASSERTIONS.requiredToKill and optionalSanityChecks templates.\n");
                sb.append("- Do not compare Collection getters with expected message Strings.\n");
                break;
            case PACKAGE_ACCESS:
                sb.append("- Keep the generated test in the exact package shown above to access package/protected members.\n");
                break;
            default:
                sb.append("- Make the smallest changes necessary to compile while preserving the mutation-sensitive assertion.\n");
                break;
        }
        sb.append('\n');

        appendCompactSection(sb, "ENTRY", e.entry);
        appendCompactSection(sb, "INVOCATION", e.invocation);
        appendCompactSection(sb, "ASSERTIONS", e.assertions);
        appendCompactSection(sb, "PUBLIC_API", e.publicApiEvidence);
        appendCompactSection(sb, "OBSERVABLE_PLAN", e.observablePlan);
        if (kind == CompileErrorKind.TEST_STUB_MISMATCH
                || kind == CompileErrorKind.FACTORY_BUILDER_MISMATCH
                || kind == CompileErrorKind.CONSTRUCTOR_MISMATCH
                || kind == CompileErrorKind.METHOD_NOT_FOUND
                || kind == CompileErrorKind.OTHER) {
            appendCompactSection(sb, "MUTATION", e.mutation);
            appendCompactSection(sb, "MUTATION_EVIDENCE", e.mutationEvidence);
            if (e.needEntryLiftedEvidence && e.entryEvidence.length() > 0) {
                appendCompactSection(sb, "ENTRY_EVIDENCE", e.entryEvidence);
            }
        }

        sb.append("Previous test code:\n");
        sb.append(lastCode == null ? "" : lastCode).append("\n\n");
        sb.append("Return only corrected Java source code.\n");
        return sb.toString();
    }

    private static void appendCompactSection(StringBuilder sb, String title, JSONObject obj) {
        if (obj == null || obj.length() == 0) {
            return;
        }
        sb.append(title).append(":\n");
        sb.append(obj.toString(2)).append("\n\n");
    }

