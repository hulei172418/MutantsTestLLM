        sb.append("- If ENTRY_GRAPH_EVIDENCE_B_CPG exists, use it only to understand how callable entry B reaches A.\n");
        sb.append("- First write package/imports, then one public test class.\n");
        sb.append("- Prefer the setup/call/assertion templates, but fix variable names if needed.\n");
        sb.append("- Use type-compatible assertions. Do not compare Collection values with message Strings.\n");
        sb.append("- For constructor entry, instantiate the object and assert public observable state/message.\n");
        sb.append("- Receiver construction is already resolved by static analysis in INVOCATION.receiver. Follow receiver.strategy exactly.\n");
        sb.append("- If receiver.strategy is CONCRETE_SUBCLASS_INHERITED_METHOD, instantiate runtimeReceiverClass and call the inherited method through that object; do NOT create an anonymous subclass.\n");
        sb.append("- If receiver.strategy is STATIC_FACTORY_BUILDER, use the setupTemplate produced by static analysis exactly; do not invent constructors or builder terminal methods.\n");
